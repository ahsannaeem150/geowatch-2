#!/usr/bin/env node
/**
 * Generate web-style incident marker PNGs for the mobile app.
 *
 * Each PNG replicates the web DOM marker (src/shared/marker-builder.js):
 * domain-colored circle + 30% white border + colored soft glow + white domain
 * icon (paths from src/shared/marker-icons.js). Canvas 256px, circle r=88 —
 * MapScreen scales them per severity (web SEVERITY_SCALE radii 6–14).
 *
 * Output:
 *   src/mobile-app/assets/markers/<slug>.png  (+ unknown.png fallback)
 *   src/mobile-app/src/screens/map/markerImages.js  (static requires for <Images>)
 *
 * Run from repo root:  node scripts/generate-mobile-markers.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import sharp from 'sharp';
import { DOMAIN_MARKER_ICONS, getMarkerIcon } from '../src/shared/marker-icons.js';
import { DOMAINS } from '../src/mobile-app/src/constants.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'src/mobile-app/assets/markers');
const MODULE_PATH = join(ROOT, 'src/mobile-app/src/screens/map/markerImages.js');

const SIZE = 256;
const R = 88;
const ICON_SCALE = (R * 1.2) / 24; // web: iconSize = radius * 1.2 (viewBox 24)

function markerSvg(color, domainSlug) {
  const icon = getMarkerIcon(domainSlug);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}">
  <defs>
    <filter id="glow" x="-60%" y="-60%" width="220%" height="220%">
      <feGaussianBlur stdDeviation="16"/>
    </filter>
  </defs>
  <circle cx="128" cy="128" r="${R}" fill="${color}" opacity="0.45" filter="url(#glow)"/>
  <circle cx="128" cy="128" r="${R}" fill="${color}" stroke="rgba(255,255,255,0.3)" stroke-width="8"/>
  <g transform="translate(128,128) scale(${ICON_SCALE}) translate(-12,-12)">
    <path d="${icon.path}" fill="none" stroke="white" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>
  </g>
</svg>`;
}

const entries = [...DOMAINS.map((d) => [d.slug, d.color]), ['unknown', '#6b7280']];

await mkdir(OUT_DIR, { recursive: true });

const requires = [];
for (const [slug, color] of entries) {
  const svg = markerSvg(color, DOMAIN_MARKER_ICONS[slug] ? slug : 'unknown');
  await sharp(Buffer.from(svg)).resize(SIZE, SIZE).png().toFile(join(OUT_DIR, `${slug}.png`));
  requires.push(`  'marker-${slug}': require('../../../assets/markers/${slug}.png'),`);
  console.log(`✓ marker-${slug}.png`);
}

const moduleSrc = `// GENERATED by scripts/generate-mobile-markers.mjs — do not edit by hand.
// Web-style incident markers (domain color + glow + white icon) for <Images>.
export const MARKER_IMAGES = {
${requires.join('\n')}
};

export function markerImageFor(domainSlug) {
  const key = \`marker-\${domainSlug}\`;
  return Object.prototype.hasOwnProperty.call(MARKER_IMAGES, key)
    ? key
    : 'marker-unknown';
}
`;
await writeFile(MODULE_PATH, moduleSrc);
console.log(`✓ markerImages.js (${entries.length} markers)`);
